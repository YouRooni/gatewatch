def country_flag(code, custom=False):
    if not isinstance(code, str) or len(code) != 2 or not code.isascii() or not code.isalpha():
        return ""
    code = code.upper()
    emoji = "".join(chr(0x1F1E6 + ord(char) - 65) for char in code)
    emoji_id = COUNTRY_FLAGS.get(code)
    return f'<tg-emoji emoji-id="{emoji_id}">{emoji}</tg-emoji>' if custom and emoji_id else emoji
